"""Builds js/games/words-data.js for the "5 Letters" game.

Usage:
    python tools/build-words.py <russian_nouns.txt> <enable1.txt>

Inputs (not stored in this repo):
    russian_nouns.txt - https://github.com/Harrix/Russian-Nouns (MIT, (c) Sergienko Anton)
    enable1.txt       - ENABLE word list (public domain), e.g. https://github.com/dolph/dictionary

The big dictionaries only decide which guesses are accepted. The words the game can pick as
the answer come from the hand-curated tools/answers-ru.txt and tools/answers-en.txt
(common words, no proper names). In Russian "ё" is folded into "е", as is usual for this game.
"""
import io
import re
import sys
from pathlib import Path

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
ROOT = Path(__file__).resolve().parent.parent
PATTERNS = {'ru': '[а-я]{5}', 'en': '[a-z]{5}'}


def read_words(path, lang):
    text = Path(path).read_text(encoding='utf-8').lower().replace('ё', 'е')
    return {w for w in text.split() if re.fullmatch(PATTERNS[lang], w)}


def read_answers(lang):
    raw = (ROOT / 'tools' / f'answers-{lang}.txt').read_text(encoding='utf-8').lower().replace('ё', 'е').split()
    bad = sorted({w for w in raw if not re.fullmatch(PATTERNS[lang], w)})
    if bad:
        sys.exit(f'{lang}: answers that are not 5 letters: {" ".join(bad)}')
    return sorted(set(raw))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    dictionaries = {'ru': read_words(sys.argv[1], 'ru'), 'en': read_words(sys.argv[2], 'en')}
    blocks = []
    for lang in ('ru', 'en'):
        answers = read_answers(lang)
        unknown = [w for w in answers if w not in dictionaries[lang]]
        extra = sorted(dictionaries[lang] - set(answers))
        print(f'{lang}: {len(answers)} answers, {len(extra)} more accepted guesses')
        if unknown:
            print(f'{lang}: answers missing from the dictionary (kept, check for typos): {" ".join(unknown)}')
        blocks.append(f"    {lang}: {{\n      answers: '{''.join(answers)}',\n      extra: '{''.join(extra)}'\n    }}")

    out = (
        '// Generated by tools/build-words.py - do not edit by hand.\n'
        '// Word lists for the "5 Letters" game, stored as back-to-back 5-letter words.\n'
        '//   answers - common words the game may pick (curated in tools/answers-*.txt)\n'
        '//   extra   - other real words that are accepted as guesses\n'
        '// Russian guesses: Russian-Nouns by Harrix (MIT, see licenses/Russian-Nouns-LICENSE.txt).\n'
        '// English guesses: ENABLE word list (public domain).\n'
        '(function () {\n'
        '  window.ArcadeWordData = {\n' + ',\n'.join(blocks) + '\n  };\n'
        '})();\n'
    )
    target = ROOT / 'js' / 'games' / 'words-data.js'
    target.write_text(out, encoding='utf-8', newline='\n')
    print(f'wrote {target} ({len(out.encode("utf-8")) // 1024} KB)')


if __name__ == '__main__':
    main()
